#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <stdbool.h>

void load_assembler(uint8_t* RAM){
  // source assembly code pointer
  RAM[0x0000] = 0x00;
  RAM[0x0001] = 0x40;

  // output machine code pointer
  RAM[0x0002] = 0x00;
  RAM[0x0003] = 0x50;

  // opcode string
  RAM[0x0004] = 0x00;
  RAM[0x0005] = 0x0F;

  // opcode offset
  RAM[0x0006] = 0x00;

  // opcode index
  RAM[0x0007] = 0x00;

  // token buffer ptr
  RAM[0x0008] = 0x01;

  // opcode start index
  RAM[0x0009] = 0x00;

  // opcode directory index
  RAM[0x000A] = 0x00;
  RAM[0x000B] = 0x10;

  // label list end indx
  RAM[0x000C] = 0x01;
  RAM[0x000D] = 0x14;

  // label list start indx
  RAM[0x000E] = 0x01;
  RAM[0x000F] = 0x14;

  // second pass
  RAM[0x0010] = 0x00;

  // directive indx
  RAM[0x0011] = 0x00;

  // directive ptr
  RAM[0x0012] = 0x00;
  RAM[0x0013] = 0x13;

  //opcode strings
  RAM[0x0F00] = 0x41; RAM[0x0F01] = 0x44; RAM[0x0F02] = 0x41; //ADC
  RAM[0x0F03] = 0x41; RAM[0x0F04] = 0x4E; RAM[0x0F05] = 0x44; //AND
  RAM[0x0F06] = 0x41; RAM[0x0F07] = 0x4E; RAM[0x0F08] = 0x44; //ASL
  RAM[0x0F09] = 0x42; RAM[0x0F0A] = 0x49; RAM[0x0F0B] = 0x54; //BIT

}